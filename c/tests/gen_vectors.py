#!/usr/bin/env python3
"""Convert the shared vectors into a C header for test_vectors.c.

Usage: gen_vectors.py <mecp-vectors.json> <upstream tests.json> <manifest.json> <out.h>

Upstream cases (mecp-org/MECP freetext/tests.json) only state validity and the
extracted fields; they are emitted with `envelope = false` so the runner skips
severity, codes and freetext.
"""

import json
import sys

FIELDS = ("pax", "gps", "timestamp", "language", "callsign", "reference", "duration")


def cstr(s):
    if s is None:
        return "NULL"
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\?':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def cbool(v):
    return "true" if v else "false"


def opt_num(v):
    return [cbool(v is not None), repr(v) if v is not None else "0"]


def ids(xs):
    return cstr(",".join(xs))


def decode_row(name, input, envelope, x):
    ex = x["extracted"]
    gps = ex["gps"]
    fields = [
        cstr(name),
        cstr(input),
        str(len(input.encode("utf-8"))),
        cbool(envelope),
        cbool(x["valid"]),
        str(x["severity"] if x["severity"] is not None else -1),
        cstr(" ".join(x["codes"])),
        cbool(x["is_drill"]),
        cstr(x["freetext"]),
        *opt_num(ex["pax"]),
        cbool(gps is not None),
        repr(float(gps["lat"])) if gps else "0.0",
        repr(float(gps["lon"])) if gps else "0.0",
        cstr(ex["timestamp"] or ""),
        cstr(ex["language"] or ""),
        cstr(ex["callsign"] or ""),
        cstr(ex["reference"] or ""),
        *opt_num(ex["duration"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def upstream_row(t):
    exp = t["expect"]
    x = {"valid": exp is not None, "severity": None, "codes": [], "is_drill": False,
         "freetext": None, "extracted": {f: (exp or {}).get(f) for f in FIELDS}}
    return decode_row("upstream: " + t["title"], t["input"], False, x)


def encode_row(c):
    x = c["expect"]
    codes = "{" + ", ".join(cstr(k) for k in c["codes"]) + "}" if c["codes"] else "{NULL}"
    fields = [
        cstr(c["name"]),
        str(c["severity"]),
        codes,
        str(len(c["codes"])),
        cstr(c["freetext"]),
        cstr(x["message"] or ""),
        str(x["byte_length"]),
        ids(x["errors"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def validate_row(c):
    x = c["expect"]
    fields = [
        cstr(c["name"]),
        cstr(c["input"]),
        str(len(c["input"].encode("utf-8"))),
        cbool(x["valid"]),
        ids(x["errors"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def main(src, upstream, manifest, dst):
    def load(p):
        with open(p, encoding="utf-8") as f:
            return json.load(f)

    v, tests = load(src), load(upstream)
    if load(manifest)["schemaVersion"] != 2:
        sys.exit("unsupported upstream schemaVersion")
    max_codes = max(len(c["codes"]) for c in v["encode"])
    lines = [
        "/* Generated by gen_vectors.py from vectors/mecp-vectors.json and",
        "   upstream/freetext/tests.json. Do not edit. */",
        f"#define ENCODE_MAX_CODES {max(max_codes, 1)}",
        "static const decode_vec_t DECODE_VECTORS[] = {",
        *(decode_row(c["name"], c["input"], True, c["expect"]) for c in v["decode"]),
        *map(upstream_row, tests),
        "};",
        "static const encode_vec_t ENCODE_VECTORS[] = {",
        *map(encode_row, v["encode"]),
        "};",
        "static const validate_vec_t VALIDATE_VECTORS[] = {",
        *map(validate_row, v["validate"]),
        "};",
        "",
    ]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(*sys.argv[1:5])
