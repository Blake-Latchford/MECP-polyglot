#!/usr/bin/env python3
"""Convert vectors/mecp-vectors.json into a C header for test_vectors.c.

Usage: gen_vectors.py <mecp-vectors.json> <out.h>
"""

import json
import sys


def cstr(s):
    if s is None:
        return "NULL"
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\?':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def cbool(v):
    return "true" if v else "false"


def opt_num(v):
    return (cbool(v is not None), repr(v) if v is not None else "0")


def ids(xs):
    return cstr(",".join(xs))


def decode_vec(c):
    x = c["expect"]
    ex = x["extracted"]
    gps = ex["gps"]
    has_count, count = opt_num(ex["count"])
    has_eta, eta = opt_num(ex["eta"])
    sev = x["severity"] if x["severity"] is not None else -1
    fields = [
        cstr(c["name"]),
        cstr(c["input"]),
        str(len(c["input"].encode("utf-8"))),
        cbool(x["valid"]),
        str(sev),
        cstr(" ".join(x["codes"])),
        cbool(x["is_drill"]),
        cstr(x["freetext"]),
        has_count, count,
        cbool(gps is not None),
        repr(float(gps["lat"])) if gps else "0.0",
        repr(float(gps["lon"])) if gps else "0.0",
        has_eta, eta,
        cstr(ex["reference"] or ""),
        cstr(ex["language"] or ""),
        cstr(ex["timestamp"] or ""),
        cstr(ex["callsign"] or ""),
        ids(x["warnings"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def encode_vec(c):
    x = c["expect"]
    codes = "{" + ", ".join(cstr(k) for k in c["codes"]) + "}" if c["codes"] else "{NULL}"
    fields = [
        cstr(c["name"]),
        str(c["severity"]),
        codes,
        str(len(c["codes"])),
        cstr(c["freetext"]),
        cstr(x["message"]),
        str(x["byte_length"]),
        cbool(x["over_limit"]),
        ids(x["warnings"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def validate_vec(c):
    x = c["expect"]
    fields = [
        cstr(c["name"]),
        cstr(c["input"]),
        str(len(c["input"].encode("utf-8"))),
        cbool(x["valid"]),
        ids(x["errors"]),
        ids(x["warnings"]),
    ]
    return "    {" + ", ".join(fields) + "},"


def main(src, dst):
    with open(src, encoding="utf-8") as f:
        v = json.load(f)
    max_codes = max(len(c["codes"]) for c in v["encode"])
    lines = [
        "/* Generated by gen_vectors.py from vectors/mecp-vectors.json. Do not edit. */",
        f"#define ENCODE_MAX_CODES {max(max_codes, 1)}",
        "static const decode_vec_t DECODE_VECTORS[] = {",
        *map(decode_vec, v["decode"]),
        "};",
        "static const encode_vec_t ENCODE_VECTORS[] = {",
        *map(encode_vec, v["encode"]),
        "};",
        "static const validate_vec_t VALIDATE_VECTORS[] = {",
        *map(validate_vec, v["validate"]),
        "};",
        "",
    ]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(*sys.argv[1:3])
