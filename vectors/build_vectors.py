    bad("not mecp", "hello world"),
    bad("lowercase prefix", "mecp/0/M01"),
    bad("BOM before prefix", "﻿MECP/0/M01"),
    bad("prefix only", "MECP/"),
    bad("missing delimiter", "MECP/0M01"),
