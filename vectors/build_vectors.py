#!/usr/bin/env python3
"""Build vectors/mecp-vectors.json from the hand-written cases below.

Expectations are written by hand from spec/conformance.md and the
@mecp/engine test suite -- never generated by running an implementation.
Each case lists only the fields that differ from the defaults; this script
expands them into full records so runners can compare whole structures.

Usage: python3 vectors/build_vectors.py   (rewrites mecp-vectors.json)
       python3 vectors/build_vectors.py --check   (exit 1 if out of date)
"""

import copy
import json
import sys
from pathlib import Path

OUT = Path(__file__).with_name("mecp-vectors.json")

DECODE_DEFAULT = {
    "valid": False,
    "severity": None,
    "codes": [],
    "is_drill": False,
    "freetext": None,
    "extracted": {
        "count": None,
        "gps": None,
        "eta": None,
        "reference": None,
        "language": None,
        "timestamp": None,
        "callsign": None,
    },
    "warnings": [],
}


def d(name, input, engine_divergence=None, **expect):
    """Decode case. `extracted` may be a partial dict.

    `engine_divergence` documents why @mecp/engine gives a different result
    (see "Divergences" in spec/conformance.md); oracle/check-engine.mts skips it.
    """
    full = copy.deepcopy(DECODE_DEFAULT)
    extracted = expect.pop("extracted", {})
    unknown = set(extracted) - set(full["extracted"])
    assert not unknown, f"{name}: unknown extracted keys {unknown}"
    full["extracted"].update(extracted)
    unknown = set(expect) - set(full)
    assert not unknown, f"{name}: unknown keys {unknown}"
    full.update(expect)
    case = {"name": name, "input": input, "expect": full}
    if engine_divergence:
        case["engine_divergence"] = engine_divergence
    return case


def ok(name, input, severity, codes=(), freetext=None, **rest):
    """Decode case for a valid message."""
    return d(name, input, valid=True, severity=severity, codes=list(codes),
             freetext=freetext, **rest)


def gps(lat, lon):
    return {"lat": lat, "lon": lon}


