    ok("tab inside freetext", "MECP/3/L01 a\tb", ["L01"], "a\tb"),
    ok("vertical tab inside freetext", "MECP/3/L01 a\x0bb", ["L01"], "a\x0bb"),
    ok("trailing CRLF removed", "MECP/2/B03\r\n", ["B03"]),
    bad("only one trailing line ending is removed", "MECP/2/B03\n\n"),
    bad("LF CR leaves an LF", "MECP/2/B03\n\r"),
    bad("embedded NEL (U+0085)", "MECP/2/B03 a\x85b"),
    bad("embedded paragraph separator (U+2029)", "MECP/2/B03 a b"),
