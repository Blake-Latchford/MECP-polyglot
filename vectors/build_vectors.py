    ft("language too long", "@english"),
    ft("language trailing hyphen", "@en-"),
    ft("language before NBSP", "@fr bonjour", language="fr"),
    ft("language and timestamp", "@1430 @de", timestamp="14:30", language="de"),

    # --- Callsign ---
    ft("callsign lowercase is uppercased", "~vk2/ok1abc/p", callsign="VK2/OK1ABC/P"),
    ft("callsign with digits", "~2E0ABC", callsign="2E0ABC"),
    ft("callsign of 13 characters", "~ABCDEFGHIJKLM"),

