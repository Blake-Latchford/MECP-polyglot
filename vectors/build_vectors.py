    bad("space before the first code", "MECP/0/ M01"),
    bad("double space between codes", "MECP/0/M01  M07"),
    bad("freetext starting with a tab", "MECP/0/M01 \tx"),
    bad("freetext ending with a tab", "MECP/0/M01 x\t"),

    # --- Drill ---
    ok("D01 is drill", "MECP/0/D01 M01 2pax", ["D01", "M01"], "2pax", is_drill=True, pax=2),
    ok("D02 is drill", "MECP/3/D02", ["D02"], is_drill=True),
    ok("D03 is not drill", "MECP/3/D03", ["D03"]),
    ok("D04 is not drill", "MECP/3/D04", ["D04"]),
    ok("D01 in freetext is not drill", "MECP/3/L01 x D01", ["L01"], "x D01"),

    # --- Person count ---
    ft("pax with a space before the unit", "4 pax", pax=4),
    ft("pax in capitals", "3PAX", pax=3),
    ft("pax inside a word is not decoded", "about12paxish"),
    ft("pax of all zeros is not decoded", "00pax"),
    ft("pax leading zeros before a long count", "0000000000000000000001pax", pax=1),
    ft("pax int32 maximum", "2147483647pax", pax=INT_MAX),
    ft("pax overflow clamps", "99999999999pax", pax=INT_MAX),
    ft("pax after a period boundary", "1.5pax", pax=5),
    ft("pax after a minus sign is not decoded", "-3pax"),
    ft("pax with Arabic-Indic digit is not decoded", "٣pax"),

    # --- GPS ---
    ft("gps south west", "-33.8688,-151.2093", gps=gps(-33.8688, -151.2093)),
